#!/usr/bin/env python3
"""Bundle the Worker modules and the two HTML entry pages into one deployable file."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = [
    "http.js",       # shared HTTP response, body, ID, and validation helpers
    "auth.js",       # staff passcode checks and public API route allowlist
    "storage.js",    # KV access and generic entity CRUD/export/reset
    "ai.js",         # allowlisted text actions and rate limiting
    "media.js",      # image/audio handling and newsletter generation
    "translate.js",  # Spanish newsletter translation
    "alumni.js",     # public program list and voluntary alumni submissions
    "pages.js",      # static staff and student HTML responses
    "index.js",      # route dispatch and Worker entry point
]
IMPORT_LINE = re.compile(r"^\s*import\s+.*\s+from\s+['\"]\./[^'\"]+['\"];\s*$", re.M)
DECLARATION = re.compile(r"^(?:export\s+)?(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)\b", re.M)


def fail(message):
    print(f"build_worker.py: error: {message}", file=sys.stderr)
    raise SystemExit(1)


def bundle_module(name, seen):
    path = ROOT / "src" / "worker" / name
    if not path.is_file():
        fail(f"missing Worker module: {path.relative_to(ROOT)}")
    text = path.read_text(encoding="utf-8")
    for symbol in DECLARATION.findall(text):
        if symbol in seen:
            fail(f"duplicate top-level name '{symbol}' in {name} (already defined in {seen[symbol]})")
        seen[symbol] = name
    text = IMPORT_LINE.sub("", text)
    text = re.sub(r"^export\s+(?!default\b)", "", text, flags=re.M)
    return f"\n// ==================== src/worker/{name} ====================\n{text.rstrip()}\n"


def main():
    if len(sys.argv) != 1:
        fail("this repo bundler takes no arguments; run python3 build/build_worker.py")
    staff_path = ROOT / "src" / "index.html"
    share_path = ROOT / "src" / "share.html"
    for path in (staff_path, share_path):
        if not path.is_file():
            fail(f"missing HTML source: {path.relative_to(ROOT)}")

    seen = {}
    pieces = []
    for name in MODULES:
        pieces.append(bundle_module(name, seen))
    bundle = "".join(pieces)
    if bundle.count("export default") != 1:
        fail("expected exactly one 'export default' in the Worker modules")

    html_constants = (
        "const STAFF_APP_HTML = " + json.dumps(staff_path.read_text(encoding="utf-8")) + ";\n"
        "const SHARE_PAGE_HTML = " + json.dumps(share_path.read_text(encoding="utf-8")) + ";\n"
    )
    output = "// GENERATED by build/build_worker.py from src/worker/*.js + src/*.html. Do not edit by hand.\n" + html_constants + bundle
    out_path = ROOT / "worker.js"
    out_path.write_text(output, encoding="utf-8")
    print(f"Wrote worker.js ({out_path.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
